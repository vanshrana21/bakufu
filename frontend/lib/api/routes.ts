/** Every backend route this app calls, declared once.
 *
 * Two things kept drifting apart and nothing caught either of them:
 *
 *   1. What the frontend requests vs. what FastAPI serves. A renamed path or a
 *      query parameter that became a body field still compiles and still passes
 *      the unit suite; it fails as a 404 in front of whoever is watching.
 *   2. What the browser requests vs. what `/api/backend` forwards. The proxy
 *      allowlist is deliberately narrow, so a loader that moves from a Server
 *      Component into a client component would start being refused by this
 *      app's own proxy.
 *
 * This table is the one place both are stated, and two tests turn it into
 * evidence rather than a claim:
 *
 *   tests/unit/route-registry.test.ts  — every entry exists in FastAPI with this
 *     method and these query parameters (backend-routes.json, regenerated by
 *     backend/scripts/export_routes.py and enforced by a backend test).
 *   tests/unit/browser-surface.test.ts — walks the import graph from every
 *     "use client" file and asserts the set of routes reachable in a browser is
 *     exactly the set marked `surface: "browser"` here.
 *
 * `surface` is the security boundary. `/api/backend` is this app's only
 * unauthenticated door to an expensive API, so it forwards the browser set and
 * nothing else. Widening it to routes the browser never calls would add reachable
 * surface and buy nothing — see docs/api-surface.md.
 */

export type RouteSurface = "browser" | "server";

export interface RouteSpec {
  /** The FastAPI path, exactly as the app declares it (`{}` for parameters). */
  readonly path: string;
  readonly method: "GET" | "POST";
  /** `browser` = reachable from a client component, so it must be proxied.
   *  `server` = only ever called from a Server Component or route handler. */
  readonly surface: RouteSurface;
  /** Query parameters this app sends. Checked against FastAPI's own list. */
  readonly query?: readonly string[];
  /** Where the request is issued, and why it sits on this surface. */
  readonly calledBy: string;
}

