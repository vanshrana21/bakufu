/** The routes the browser may reach, as `path without leading slash -> method`.
 *
 * Parameterised paths cannot be matched by the proxy's exact lookup, so a
 * browser route carrying `{}` is a build-time error here rather than a 404 that
 * only appears when someone clicks the feature.
 */
export const BROWSER_ROUTES: Readonly<Record<string, "GET" | "POST">> = Object.freeze(
  Object.fromEntries(
    API_ROUTES.filter((route) => route.surface === "browser").map((route) => {
      if (route.path.includes("{")) {
        throw new Error(
          `Browser route ${route.path} has a path parameter, which the proxy cannot match. ` +
            `Give it an exact path or move it to the server surface.`,
        );
      }
      return [route.path.replace(/^\//, ""), route.method];
    }),
  ),
);

/** Routes deliberately NOT reachable from the browser, for the proxy tests and
 * the documentation to assert against. */
export const SERVER_ONLY_ROUTES: readonly RouteSpec[] = API_ROUTES.filter(
  (route) => route.surface === "server",
);
